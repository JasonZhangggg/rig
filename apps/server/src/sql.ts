// The database connection: Postgres, reached through Cloudflare Hyperdrive in
// production (it pools connections near the database) or a plain connection
// string for local runs. One connection pool per request, as Workers require.

import { Kysely, PostgresDialect, type ColumnType, type Generated } from "kysely";
import pg from "pg";
import type { Env } from "./env";

// Postgres bigint comes back as a string by default. Rig's bigints are
// millisecond times, which fit in a JS number.
pg.types.setTypeParser(20, (v) => Number(v));

type Json<T> = ColumnType<T, string, string>;
type Time = ColumnType<Date, Date | string, Date | string>;

/** Rig's own tables. Better Auth reaches its tables through the same connection. */
export interface RigTables {
  machine: {
    user_id: string; id: string;
    view: Json<unknown>; inventory: Json<unknown> | null; facts: Json<unknown> | null;
    changes: Json<unknown[]>; games: Json<unknown[]>; identity: Json<Record<string, unknown>>;
    identity_at: Time | null; synced_at: Time; created_at: Generated<Date>;
    events: ColumnType<unknown[], string | undefined, string>;
  };
  recording: {
    user_id: string; machine_id: string; id: string; state: string;
    info: Json<unknown>; data: ColumnType<unknown, string | undefined, string>;
    stop_requested: Generated<boolean>; created_at: Time; updated_at: Time;
  };
  machine_history: {
    user_id: string; machine_id: string; t: number; cpu: number | null; gpu: number | null; busy: boolean;
    fan: number | null; game: string | null;
    cpu_load: number | null; gpu_load: number | null; mem: number | null; drive: number | null; board: number | null;
  };
  chat_usage: { user_id: string; day: string; count: number };
  manual_sources: {
    key: string; url: string | null; title: string | null; host: string | null; bytes: number | null;
    found_at: Time | null; missed_at: Time | null;
  };
  manuals: {
    id: string; user_id: string; machine_id: string; part: string; kind: string; maker: string; model: string; title: string;
    url: string | null; host: string | null; source: string; page_count: number | null; indexed: Generated<boolean>;
    diagrams: ColumnType<unknown[], string | undefined, string>; bytes: number | null; added_at: Time;
  };
  /** tsv is generated by Postgres from text, so it's left out here. */
  manual_pages: { manual_id: string; n: number; text: string };
}

/** The columns of Better Auth's tables that Rig reads or clears itself (export and account deletion). */
export interface AuthTables {
  user: { id: string; name: string; email: string; createdAt: Time };
  session: { id: string; userId: string };
  account: { id: string; userId: string };
  deviceCode: { id: string; userId: string | null };
}

export type DB = Kysely<RigTables & AuthTables>;

export interface Connection { db: DB; close(): Promise<void> }

export function connect(env: Env): Connection {
  const connectionString = env.HYPERDRIVE?.connectionString ?? env.DATABASE_URL;
  if (!connectionString) throw new Error("No database: set the HYPERDRIVE binding or DATABASE_URL.");
  const pool = new pg.Pool({ connectionString, max: 5 });
  const db = new Kysely<RigTables & AuthTables>({ dialect: new PostgresDialect({ pool }) });
  return { db, close: () => db.destroy() };
}
